/** Legacy ids generated by older builds; still rendered, no longer offered as presets. */
const LEGACY_DIRECTIONS = [
  "north",
  "northeast",
  "east",
  "southeast",
  "south",
  "southwest",
  "west",
  "northwest",
];
const ALIAS: Record<string, string> = { zoom: "zoom-in", wipe: "wipe-right" };
export const transitionName = (id: string) => {
  const key = ALIAS[id] ?? id;
  const hit = TRANSITIONS.find((t) => t.id === key);
  if (hit) return hit.name;
  // diagonal variants saved by older projects read back as "Slide Northeast" instead of a raw id
  const legacy = /^vector-(slide|push|wipe|zoom)-(\d)$/.exec(key);
  if (legacy) {
    const family = legacy[1]!.charAt(0).toUpperCase() + legacy[1]!.slice(1);
    return `${family} ${LEGACY_DIRECTIONS[Number(legacy[2])] ?? ""}`.trim();
  }
  return id;
};

const ease = (p: number) => (p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2);

/** Gap tolerance (s) for treating two clips on a track as adjacent. */
export const ADJ_EPS = 0.05;

/** The clip immediately before `c` on the track (touching it), if any. */
export function prevAdjacent(track: Track, c: Clip): Clip | null {
  let best: Clip | null = null;
  for (const o of track.clips) {
    if (o.id === c.id) continue;
    // clips may now share a lane with effect blocks or audio, which draw no layer to blend
    if (!isVisualClip(o)) continue;
    if (Math.abs(clipEnd(o) - c.start) <= ADJ_EPS) best = o;
  }
  return best;
}
export function nextAdjacent(track: Track, c: Clip): Clip | null {
  const e = clipEnd(c);
  for (const o of track.clips)
    if (o.id !== c.id && isVisualClip(o) && Math.abs(o.start - e) <= ADJ_EPS) return o;
  return null;
}

/** Extra time a clip stays visible after its end, as the outgoing side of the next clip's transition. */
export function outgoingTail(track: Track, c: Clip): number {
  const n = nextAdjacent(track, c);
  return n?.transitionIn && n.transitionIn.duration > 0 ? n.transitionIn.duration : 0;
}

/**
 * Largest editable duration for a seam transition. The blend reveals the clip it belongs to and
 * holds the material before the cut, so it can never run longer than that clip or longer than the
 * outgoing side of the join. A clip with nothing touching in front of it still reveals itself.
 * Resizing within this ceiling never changes either clip's length - the transition is its own item.
 */
export function maxTransitionDuration(prev: Clip | null, next: Clip): number {
  const body = clipDuration(next) * 0.9;
  const cap = prev ? Math.min(clipDuration(prev), body) : body;
  return Math.max(0.1, Math.min(5, cap));
}

/**
 * The timeline window a clip's in-transition actually occupies. The engine holds the previous
 * clip's picture past its end and reveals this clip over it, so the blend always runs from the
 * clip's own start. Clip rectangles keep their full width, so trimming a blend never shortens video.
 */
export function transitionInSpan(c: Clip): { start: number; duration: number } | null {
  const t = c.transitionIn;
  if (!t || t.duration <= 0 || !isVisualClip(c)) return null;
  return { start: c.start, duration: Math.min(t.duration, clipDuration(c)) };
}

/**
 * Where the lane draws that transition: its own block sitting on the joint so it belongs to neither
 * clip - half over the outgoing clip, half over the incoming one. `bias` lets the centre slide off
 * the cut when an edge is trimmed on its own (the opposite edge holds), while the blend still spans
 * `duration` seconds and the width stays the dissolve it performs. `center` is where the block aims.
 */
export function transitionBlockSpan(
  c: Clip,
): { center: number; start: number; duration: number } | null {
  const span = transitionInSpan(c);
  if (!span) return null;
  const bias = c.transitionIn?.bias ?? 0;
  const center = span.start + bias;
  return { center, start: center - span.duration / 2, duration: span.duration };
}

type Layer = HTMLCanvasElement | null;

function put(
  ctx: CanvasRenderingContext2D,
  L: Layer,
  o: {
    a?: number;
    x?: number;
    y?: number;
    s?: number;
    r?: number;
    clip?: (x: CanvasRenderingContext2D) => void;
  } = {},
) {
  if (!L) return;
  const W = ctx.canvas.width,
    H = ctx.canvas.height;
  ctx.save();
  if (o.clip) {
    ctx.beginPath();
    o.clip(ctx);
    ctx.clip();
  }
  ctx.globalAlpha = Math.max(0, Math.min(1, o.a ?? 1));
  ctx.translate(W / 2 + (o.x ?? 0), H / 2 + (o.y ?? 0));
  if (o.r) ctx.rotate(o.r);
  const s = o.s ?? 1;
  ctx.scale(s, s);
  ctx.drawImage(L, -W / 2, -H / 2);
  ctx.restore();
}

function fill(ctx: CanvasRenderingContext2D, color: string, a: number) {
  if (a <= 0) return;
  ctx.save();
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.globalAlpha = Math.min(1, a);
  ctx.fillStyle = color;
  ctx.fillRect(0, 0, ctx.canvas.width, ctx.canvas.height);
  ctx.restore();
}

function processed(L: Layer, key: string, fn: (c: HTMLCanvasElement) => void): Layer {
  if (!L) return null;
  const c = poolCanvas(key, L.width, L.height);
  clear(c);
  ctx2d(c).drawImage(L, 0, 0);
  fn(c);
  return c;
}

function heartPath(x: CanvasRenderingContext2D, cx: number, cy: number, s: number) {
  x.moveTo(cx, cy + s * 0.35);
  x.bezierCurveTo(cx - s * 1.1, cy - s * 0.35, cx - s * 0.5, cy - s * 1.05, cx, cy - s * 0.45);
  x.bezierCurveTo(cx + s * 0.5, cy - s * 1.05, cx + s * 1.1, cy - s * 0.35, cx, cy + s * 0.35);
}

/** Radial (zoom) blur: repeated copies smeared outward from the center. */
function radialStreak(c: HTMLCanvasElement, amount: number) {
  if (amount <= 0.01) return;
  const W = c.width,
    H = c.height;
  const src = poolCanvas("tr-zb-src", W, H);
  clear(src);
  ctx2d(src).drawImage(c, 0, 0);
  const x = ctx2d(c);
  x.save();
  for (let i = 1; i <= 8; i++) {
    const sc = 1 + i * 0.035 * amount;
    x.globalAlpha = 0.3 / i;
    x.drawImage(src, (W - W * sc) / 2, (H - H * sc) / 2, W * sc, H * sc);
  }
  x.restore();
}

/**
 * Composite a transition at progress p (0..1) from layer `from` to layer `to`.
 * A null layer means "nothing" (lower tracks show through).
 */
export function drawTransition(
  ctx: CanvasRenderingContext2D,
  typeIn: string,
  pRaw: number,
  from: Layer,
  to: Layer,
) {
  const type = ALIAS[typeIn] ?? typeIn;
  const W = ctx.canvas.width,
    H = ctx.canvas.height;
  const p = Math.max(0, Math.min(1, pRaw));
  const e = ease(p);
  const diag = Math.hypot(W, H);
  if (type.startsWith("vector-")) {
    const [, family, index] = type.split("-");
    const angle = (Number(index) * Math.PI) / 4 - Math.PI / 2;
    const dx = Math.cos(angle),
      dy = Math.sin(angle);
    if (family === "slide" || family === "push") {
      put(ctx, from, family === "push" ? { x: -dx * W * e, y: -dy * H * e } : {});
      put(ctx, to, { x: dx * W * (1 - e), y: dy * H * (1 - e) });
    } else if (family === "zoom") {
      put(ctx, from, { s: 1 + e * 0.5, x: dx * W * e * 0.2, y: dy * H * e * 0.2 });
      put(ctx, to, { s: 0.2 + e * 0.8, x: dx * W * (1 - e), y: dy * H * (1 - e), a: p });
    } else {
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          // Half-plane reveal perpendicular to the requested direction.
          const extent = Math.abs(dx) * W + Math.abs(dy) * H;
          const edge = -extent / 2 + extent * e;
          const cx = W / 2 + dx * edge,
            cy = H / 2 + dy * edge;
          x.moveTo(cx - dy * diag, cy + dx * diag);
          x.lineTo(cx + dy * diag, cy - dx * diag);
          x.lineTo(cx + dy * diag - dx * diag * 2, cy - dx * diag - dy * diag * 2);
          x.lineTo(cx - dy * diag - dx * diag * 2, cy + dx * diag - dy * diag * 2);
          x.closePath();
        },
      });
    }
    return;
  }
  switch (type) {
    case "cross-swipe":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          x.rect(0, H / 2 - (H * e) / 2, W, H * e);
          x.rect(W / 2 - (W * e) / 2, 0, W * e, H);
        },
      });
      return;
    case "checker":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          for (let y = 0; y < 6; y++)
            for (let col = 0; col < 8; col++) {
              const q = Math.min(1, Math.max(0, e * 2 - ((y + col) % 2) * 0.5));
              x.rect((col * W) / 8, (y * H) / 6, (W / 8) * q, (H / 6) * q);
            }
        },
      });
      return;
    case "three-slides": {
      put(ctx, from);
      for (let band = 0; band < 3; band++)
        put(ctx, to, {
          x: (band % 2 ? -1 : 1) * W * (1 - e),
          clip: (x) => x.rect(0, (band * H) / 3, W, H / 3),
        });
      return;
    }
    case "diagonal":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const edge = (W + H) * e;
          x.moveTo(0, 0);
          x.lineTo(edge, 0);
          x.lineTo(edge - H, H);
          x.lineTo(0, H);
          x.closePath();
        },
      });
      return;
    case "splitting-laser":
      put(ctx, from);
      put(ctx, to, { clip: (x) => x.rect(W / 2 - (W * e) / 2, 0, W * e, H) });
      if (p > 0 && p < 1) {
        ctx.save();
        ctx.fillStyle = "#fff";
        ctx.fillRect(W / 2 - (W * e) / 2, 0, 2, H);
        ctx.fillRect(W / 2 + (W * e) / 2, 0, 2, H);
        ctx.restore();
      }
      return;
    case "tv-off": {
      const L = p < 0.5 ? from : to;
      const sy = Math.max(0.005, Math.abs(2 * p - 1));
      ctx.save();
      ctx.translate(0, H / 2);
      ctx.scale(1, sy);
      ctx.translate(0, -H / 2);
      put(ctx, L);
      ctx.restore();
      return;
    }
    case "liquid-morph": {
      const L = p < 0.5 ? from : to;
      if (!L) return;
      const strength = Math.sin(p * Math.PI);
      const warped = processed(L, "tr-liquid", (c) => {
        const src = poolCanvas("tr-liquid-copy", W, H);
        clear(src);
        ctx2d(src).drawImage(c, 0, 0);
        clear(c);
        const cx = ctx2d(c);
        for (let y = 0; y < H; y += 3)
          cx.drawImage(
            src,
            0,
            y,
            W,
            3,
            Math.sin((y / H) * 18 + p * 12) * W * 0.08 * strength,
            y,
            W,
            3,
          );
      });
      put(ctx, warped);
      return;
    }
    case "blaze-fall":
      put(ctx, from, { y: H * e, a: 1 - p });
      put(ctx, to, { y: -H * (1 - e), a: p });
      fill(ctx, "#ff8b38", Math.sin(p * Math.PI) * 0.35);
      return;
    case "fade":
      if (to && from) {
        put(ctx, from);
        put(ctx, to, { a: p });
      } else {
        put(ctx, from, { a: 1 - p });
        put(ctx, to, { a: p });
      }
      return;
    case "dip-black":
    case "dip-white": {
      const col = type === "dip-black" ? "#000" : "#fff";
      if (p < 0.5) {
        put(ctx, from);
        fill(ctx, col, p * 2);
      } else {
        put(ctx, to);
        fill(ctx, col, (1 - p) * 2);
      }
      return;
    }
    case "blur": {
      const amt = Math.sin(p * Math.PI) * 40 * (H / 1080);
      put(
        ctx,
        processed(from, "tr-a", (c) => blurInPlace(c, amt)),
        { a: from && to ? 1 : 1 - p },
      );
      put(
        ctx,
        processed(to, "tr-b", (c) => blurInPlace(c, amt)),
        { a: p },
      );
      return;
    }
    case "slide-left":
    case "slide-right":
    case "slide-up":
    case "slide-down": {
      const [dx, dy] =
        type === "slide-left"
          ? [W, 0]
          : type === "slide-right"
            ? [-W, 0]
            : type === "slide-up"
              ? [0, H]
              : [0, -H];
      put(ctx, from);
      put(ctx, to, { x: dx * (1 - e), y: dy * (1 - e) });
      return;
    }
    case "push-left":
    case "push-right":
    case "push-up":
    case "push-down": {
      const [dx, dy] =
        type === "push-left"
          ? [W, 0]
          : type === "push-right"
            ? [-W, 0]
            : type === "push-up"
              ? [0, H]
              : [0, -H];
      put(ctx, from, { x: -dx * e, y: -dy * e });
      put(ctx, to, { x: dx * (1 - e), y: dy * (1 - e) });
      return;
    }
    case "whip": {
      const amt = Math.sin(p * Math.PI) * 60 * (W / 1920);
      if (p < 0.5)
        put(
          ctx,
          processed(from, "tr-a", (c) => blurInPlace(c, amt)),
          { x: -W * e * 0.6 },
        );
      else
        put(
          ctx,
          processed(to, "tr-b", (c) => blurInPlace(c, amt)),
          { x: W * (1 - e) * 0.6 },
        );
      return;
    }
    case "wipe-right":
    case "wipe-left":
    case "wipe-down":
    case "wipe-up": {
      put(ctx, from);
      put(ctx, to, {
        clip: (x) =>
          type === "wipe-right"
            ? x.rect(0, 0, W * e, H)
            : type === "wipe-left"
              ? x.rect(W * (1 - e), 0, W * e, H)
              : type === "wipe-down"
                ? x.rect(0, 0, W, H * e)
                : x.rect(0, H * (1 - e), W, H * e),
      });
      return;
    }
    case "doors":
      put(ctx, from);
      put(ctx, to, { clip: (x) => x.rect(W / 2 - (W / 2) * e, 0, W * e, H) });
      return;
    case "clock":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          x.moveTo(W / 2, H / 2);
          x.arc(W / 2, H / 2, diag, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2 * e);
          x.closePath();
        },
      });
      return;
    case "iris":
      put(ctx, from);
      put(ctx, to, { clip: (x) => x.arc(W / 2, H / 2, (diag / 2) * e, 0, Math.PI * 2) });
      return;
    case "diamond":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const r = diag * e;
          x.moveTo(W / 2, H / 2 - r);
          x.lineTo(W / 2 + r, H / 2);
          x.lineTo(W / 2, H / 2 + r);
          x.lineTo(W / 2 - r, H / 2);
          x.closePath();
        },
      });
      return;
    case "heart":
      put(ctx, from);
      put(ctx, to, { clip: (x) => heartPath(x, W / 2, H / 2, diag * 1.2 * e) });
      return;
    case "blinds": {
      put(ctx, from);
      const n = 8;
      put(ctx, to, {
        clip: (x) => {
          const bw = W / n;
          for (let i = 0; i < n; i++) x.rect(i * bw, 0, bw * e, H);
        },
      });
      return;
    }
    case "zoom-in":
      put(ctx, from, { s: 1 + e * 1.5, a: 1 - p });
      put(ctx, to, { s: 0.7 + 0.3 * e, a: p });
      return;
    case "zoom-out":
      put(ctx, from, { s: 1 - 0.4 * e, a: 1 - p });
      put(ctx, to, { s: 2 - e, a: p });
      return;
    case "spin":
      if (p < 0.5) put(ctx, from, { r: e * Math.PI, s: 1 - e * 0.8 });
      else put(ctx, to, { r: -(1 - e) * Math.PI, s: 0.2 + 0.8 * e });
      return;
    case "flash-zoom":
      if (p < 0.5) put(ctx, from, { s: 1 + e * 0.6 });
      else put(ctx, to, { s: 1.6 - 0.6 * e });
      fill(ctx, "#fff", Math.pow(Math.sin(p * Math.PI), 3));
      return;
    case "pixelate": {
      const size = 2 + Math.sin(p * Math.PI) * 60 * (H / 1080);
      const L = p < 0.5 ? from : to;
      put(
        ctx,
        processed(L, "tr-a", (c) => pixelate(c, size)),
      );
      return;
    }
    case "glitch": {
      const L = p < 0.5 ? from : to;
      const amt = Math.sin(p * Math.PI) * 40 * (W / 1920);
      put(
        ctx,
        processed(L, "tr-a", (c) => rgbSplit(c, amt, amt / 4)),
        { x: (Math.sin(p * 90) * amt) / 2 },
      );
      return;
    }
    case "dissolve": {
      put(ctx, from);
      const cols = 12,
        rows = 8;
      put(ctx, to, {
        clip: (x) => {
          for (let yy = 0; yy < rows; yy++)
            for (let xx = 0; xx < cols; xx++) {
              if (rand(xx * 91 + yy * 17 + 3) < e)
                x.rect((xx * W) / cols, (yy * H) / rows, W / cols + 1, H / rows + 1);
            }
        },
      });
      return;
    }
    case "flip-x":
    case "flip-y": {
      const L = p < 0.5 ? from : to;
      const sc = Math.max(0.001, Math.abs(1 - 2 * p));
      ctx.save();
      ctx.translate(W / 2, H / 2);
      ctx.scale(type === "flip-x" ? sc : 1, type === "flip-x" ? 1 : sc);
      ctx.translate(-W / 2, -H / 2);
      put(ctx, L);
      ctx.restore();
      return;
    }
    case "swing":
      if (p < 0.5) put(ctx, from, { r: -e * 0.6, x: -W * e * 1.4, a: 1 - p * 2 });
      else put(ctx, to, { r: 0.6 * (1 - e), x: W * (1 - e) * 1.4, a: (p - 0.5) * 2 });
      return;
    case "spiral":
      if (p < 0.5) put(ctx, from, { r: e * Math.PI * 2, s: 1 - e * 0.9, a: 1 - p * 2 });
      else put(ctx, to, { r: (1 - e) * Math.PI * 2 - Math.PI, s: 0.1 + e * 0.9, a: (p - 0.5) * 2 });
      return;
    case "fan":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const blades = 6;
          for (let i = 0; i < blades; i++) {
            const a0 = (i * Math.PI * 2) / blades;
            x.moveTo(W / 2, H / 2);
            x.arc(W / 2, H / 2, diag, a0, a0 + ((Math.PI * 2) / blades) * e);
          }
        },
      });
      return;
    case "hourglass":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          x.rect(W / 2 - (W * e) / 2, 0, W * e, H);
          x.rect(0, H / 2 - (H * e) / 2, W, H * e);
        },
      });
      return;
    case "blinds-rows": {
      put(ctx, from);
      const n = 8,
        bh = H / n;
      put(ctx, to, {
        clip: (x) => {
          for (let i = 0; i < n; i++) x.rect(0, i * bh, W, bh * e);
        },
      });
      return;
    }
    case "wind": {
      const amt = Math.sin(p * Math.PI) * 40 * (W / 1920);
      put(
        ctx,
        processed(from, "tr-a", (c) => blurInPlace(c, amt)),
        { x: -W * e * 0.5, a: 1 - p },
      );
      put(
        ctx,
        processed(to, "tr-b", (c) => blurInPlace(c, amt)),
        { x: W * (1 - e) * 0.5, a: p },
      );
      return;
    }
    case "cube": {
      if (from) {
        ctx.save();
        ctx.scale(Math.max(0.02, 1 - e), 1);
        ctx.drawImage(from, 0, 0, W, H);
        ctx.restore();
      }
      if (to) {
        ctx.save();
        ctx.translate(W, 0);
        ctx.scale(Math.max(0.02, e), 1);
        ctx.drawImage(to, -W, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "fold": {
      if (from) {
        ctx.save();
        ctx.scale(1, Math.max(0.02, 1 - e));
        ctx.drawImage(from, 0, 0, W, H);
        ctx.restore();
      }
      if (to) {
        ctx.save();
        ctx.translate(0, H);
        ctx.scale(1, Math.max(0.02, e));
        ctx.drawImage(to, 0, -H, W, H);
        ctx.restore();
      }
      return;
    }
    case "perspective": {
      if (from) {
        ctx.save();
        ctx.globalAlpha = 1 - e;
        ctx.translate(W / 2, H / 2);
        ctx.transform(1, 0, -0.3 * e, 1 - 0.15 * e, 0, 0);
        ctx.translate(-W / 2, -H / 2);
        ctx.drawImage(from, 0, 0, W, H);
        ctx.restore();
      }
      if (to) {
        ctx.save();
        ctx.globalAlpha = e;
        const s = 0.75 + 0.25 * e;
        ctx.translate(W / 2, H / 2);
        ctx.transform(s, 0, 0.3 * (1 - e), s, 0, 0);
        ctx.translate(-W / 2, -H / 2);
        ctx.drawImage(to, 0, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "page-turn": {
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const fx = W * (1 - e);
          x.moveTo(fx, 0);
          x.lineTo(W, 0);
          x.lineTo(W, H);
          x.lineTo(fx, H);
          x.lineTo(fx - H * 0.15, H / 2);
          x.closePath();
        },
      });
      if (p > 0 && p < 1) {
        const fx = W * (1 - e),
          sw = 30 * (W / 1920);
        ctx.save();
        const g = ctx.createLinearGradient(fx - sw, 0, fx, 0);
        g.addColorStop(0, "rgba(0,0,0,0)");
        g.addColorStop(1, "rgba(0,0,0,0.35)");
        ctx.fillStyle = g;
        ctx.fillRect(fx - sw, 0, sw, H);
        ctx.restore();
      }
      return;
    }
    case "film-burn": {
      put(ctx, from, { a: 1 - p });
      put(ctx, to, { a: p });
      const b = Math.sin(p * Math.PI);
      if (b > 0.01) {
        ctx.save();
        ctx.globalCompositeOperation = "lighter";
        ctx.globalAlpha = b * 0.85;
        const g = ctx.createRadialGradient(W / 2, H / 2, 0, W / 2, H / 2, Math.hypot(W, H) / 2);
        g.addColorStop(0, "rgba(255,220,150,0.9)");
        g.addColorStop(0.5, "rgba(255,120,40,0.5)");
        g.addColorStop(1, "rgba(255,60,0,0)");
        ctx.fillStyle = g;
        ctx.fillRect(0, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "light-leak": {
      put(ctx, from, { a: 1 - p });
      put(ctx, to, { a: p });
      const b = Math.sin(p * Math.PI);
      if (b > 0.01) {
        ctx.save();
        ctx.globalCompositeOperation = "screen";
        ctx.globalAlpha = b * 0.7;
        const g = ctx.createLinearGradient(0, 0, W, H);
        g.addColorStop(0, "rgba(255,140,60,0.6)");
        g.addColorStop(0.5, "rgba(255,80,120,0.3)");
        g.addColorStop(1, "rgba(255,200,80,0.6)");
        ctx.fillStyle = g;
        ctx.fillRect(0, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "dream-dissolve": {
      const amt = Math.sin(p * Math.PI) * 30 * (H / 1080);
      put(
        ctx,
        processed(from, "tr-a", (c) => blurInPlace(c, amt)),
        { a: from && to ? 1 : 1 - p },
      );
      put(
        ctx,
        processed(to, "tr-b", (c) => blurInPlace(c, amt)),
        { a: p },
      );
      const b = Math.sin(p * Math.PI);
      if (b > 0.01) {
        ctx.save();
        ctx.globalCompositeOperation = "lighter";
        ctx.globalAlpha = b * 0.3;
        ctx.fillStyle = "#fff";
        ctx.fillRect(0, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "glow": {
      put(ctx, from, { a: 1 - p });
      put(ctx, to, { a: p });
      const b = Math.sin(p * Math.PI);
      if (b > 0.01) {
        ctx.save();
        ctx.globalCompositeOperation = "lighter";
        ctx.globalAlpha = b * 0.5;
        const g = ctx.createRadialGradient(W / 2, H / 2, 0, W / 2, H / 2, Math.max(W, H) * 0.6);
        g.addColorStop(0, "rgba(255,255,255,0.8)");
        g.addColorStop(1, "rgba(255,255,255,0)");
        ctx.fillStyle = g;
        ctx.fillRect(0, 0, W, H);
        ctx.restore();
      }
      return;
    }
    case "warp-zoom": {
      put(ctx, from, { s: 1 + (1 - e) * 1.2, a: 1 - p });
      put(ctx, to, { s: 0.3 + 0.7 * e, a: p });
      if (p > 0.02 && p < 0.98) {
        ctx.save();
        ctx.globalCompositeOperation = "screen";
        ctx.globalAlpha = Math.sin(p * Math.PI) * 0.25;
        const src = to ?? from;
        if (src)
          for (let i = 1; i <= 5; i++) {
            const k = 1 + i * 0.05;
            ctx.drawImage(src, (W - W * k) / 2, (H - H * k) / 2, W * k, H * k);
          }
        ctx.restore();
      }
      return;
    }
    case "iris-rect": {
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const rw = W * e,
            rh = H * e;
          x.rect(W / 2 - rw / 2, H / 2 - rh / 2, rw, rh);
        },
      });
      return;
    }
    // Squeeze: one frame is pressed flat against the centre line, the other expands out of it.
    case "squeeze": {
      const pairs: readonly [Layer, number, number][] = [
        [from, Math.max(0.002, 1 - e), 1],
        [to, Math.max(0.002, e), Math.min(1, e * 2)],
      ];
      for (const [L, sx, a] of pairs) {
        if (!L) continue;
        ctx.save();
        ctx.globalAlpha = a;
        ctx.translate(W / 2, 0);
        ctx.scale(sx, 1);
        ctx.drawImage(L, -W / 2, 0, W, H);
        ctx.restore();
      }
      return;
    }
    // Split: the outgoing frame tears apart top/bottom and the incoming one settles behind it.
    case "split-slide": {
      put(ctx, to, { s: 1 + 0.12 * (1 - e) });
      put(ctx, from, { clip: (x) => x.rect(0, 0, W, H / 2 + 1), y: -H * e });
      put(ctx, from, { clip: (x) => x.rect(0, H / 2 - 1, W, H / 2 + 1), y: H * e });
      return;
    }
    // Ripple: a wavy edge sweeps across instead of a straight wipe line.
    case "ripple": {
      put(ctx, from);
      if (to) {
        const step = Math.max(2, Math.round(H / 40));
        const amp = W * 0.08 * Math.sin(p * Math.PI);
        for (let y = 0; y < H; y += step) {
          const edge = W * e + amp * Math.sin((y / H) * 9 + p * 10);
          ctx.save();
          ctx.beginPath();
          ctx.rect(0, y, Math.max(0, edge), step + 1);
          ctx.clip();
          ctx.drawImage(to, 0, 0, W, H);
          ctx.restore();
        }
      }
      return;
    }
    // Shatter: the outgoing frame breaks into shards that fly outward as it fades.
    case "shatter": {
      if (from) {
        const cols = 9,
          rows = 6,
          pw = W / cols,
          ph = H / rows;
        ctx.save();
        for (let r = 0; r < rows; r++) {
          for (let c = 0; c < cols; c++) {
            const seed = r * 31 + c * 7;
            const dirx = (c + 0.5) / cols - 0.5,
              diry = (r + 0.5) / rows - 0.5;
            const dist = 0.3 + rand(seed) * 0.55;
            ctx.globalAlpha = Math.max(0, 1 - e * 1.5);
            ctx.drawImage(
              from,
              c * pw,
              r * ph,
              pw + 1,
              ph + 1,
              c * pw + dirx * W * dist * e,
              r * ph + diry * H * dist * e,
              pw + 1,
              ph + 1,
            );
          }
        }
        ctx.restore();
      }
      put(ctx, to, { a: Math.min(1, e * 1.5), s: 0.9 + 0.1 * e });
      return;
    }
    // Zoom blur: both frames pass through a radial smear instead of a gaussian one.
    case "zoom-blur": {
      const amt = Math.sin(p * Math.PI) * 1.6;
      put(
        ctx,
        processed(from, "tr-zb-a", (c) => radialStreak(c, amt)),
        { a: 1 - p },
      );
      put(
        ctx,
        processed(to, "tr-zb-b", (c) => radialStreak(c, amt)),
        { a: p },
      );
      return;
    }
    // Prism: chromatic fringes spread while the frames counter-zoom through each other.
    case "prism": {
      const k = Math.sin(p * Math.PI);
      const fringe = (c: HTMLCanvasElement) => {
        rgbSplit(c, k * c.width * 0.02, 0);
        radialStreak(c, k);
      };
      put(ctx, processed(from, "tr-pr-a", fringe), { s: 1 + e * 0.25, a: 1 - p });
      put(ctx, processed(to, "tr-pr-b", fringe), { s: 1.25 - 0.25 * e, a: p });
      return;
    }
    case "star":
      put(ctx, from);
      put(ctx, to, {
        clip: (x) => {
          const r = diag * 0.72 * e,
            points = 5;
          for (let i = 0; i < points * 2; i++) {
            const a = (i * Math.PI) / points - Math.PI / 2;
            const rr = i % 2 ? r * 0.45 : r;
            const px = W / 2 + Math.cos(a) * rr,
              py = H / 2 + Math.sin(a) * rr;
            if (i) x.lineTo(px, py);
            else x.moveTo(px, py);
          }
          x.closePath();
        },
      });
      return;
    // Circle push: the incoming frame grows out of an expanding disc while the old one drifts off.
    case "iris-push": {
      if (to) {
        ctx.save();
        ctx.beginPath();
        ctx.arc(W / 2, H / 2, (diag / 2) * Math.min(1, e * 1.15), 0, Math.PI * 2);
        ctx.clip();
        const s = 1.25 - 0.25 * e;
        ctx.drawImage(to, (W - W * s) / 2, (H - H * s) / 2, W * s, H * s);
        ctx.restore();
      }
      put(ctx, from, {
        x: -W * 0.12 * e,
        y: -H * 0.12 * e,
        s: 1 + 0.25 * e,
        a: Math.max(0, 1 - e * 1.3),
      });
      return;
    }
    default:
      put(ctx, from, { a: 1 - p });
      put(ctx, to, { a: p });
  }
}

